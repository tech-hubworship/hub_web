/** 책의 장 번호 목록 (1부터) */
export function getBibleChapters(shortName: string): number[] {
  const book = BIBLE_INDEX.find((b) => b.short_name === shortName);
  return book ? book.chapters.map((_, i) => i + 1) : [];
}

/** 해당 장의 절 번호 목록 */
export function getBibleVerses(shortName: string, chapter: number): number[] {
  const book = BIBLE_INDEX.find((b) => b.short_name === shortName);
  const info = book?.chapters[chapter - 1];
  if (info == null) return [];
  return Array.isArray(info) ? info : Array.from({ length: info }, (_, i) => i + 1);
}
